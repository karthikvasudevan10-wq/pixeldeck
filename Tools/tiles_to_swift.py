#!/usr/bin/env python3
"""Turns the design's tile and stamp PNGs (Design/v2/assets) into Swift source for the app:
PixelDeck/Core/StarterTiles.swift and PixelDeck/Core/StarterStamps.swift.

Each picture becomes a palette and rows of characters ('.' is transparent; 0-9a-z index the
palette). Needs Pillow. Run from the repository root:  python3 Tools/tiles_to_swift.py
"""
from math import gcd
from functools import reduce
from PIL import Image

ASSETS = "Design/v2/assets/"
KEYS = "0123456789abcdefghijklmnopqrstuvwxyz"


def native(path, scale=None):
    """The picture at one image pixel per art pixel (the PNGs are enlarged)."""
    im = Image.open(path).convert("RGBA")
    if scale is None:
        # The enlargement is the largest step every run of equal pixels is a multiple of.
        runs = []
        px = im.load()
        for y in range(im.height):
            run = 1
            for x in range(1, im.width):
                if px[x, y] == px[x - 1, y]:
                    run += 1
                else:
                    runs.append(run)
                    run = 1
            runs.append(run)
        scale = reduce(gcd, runs)
    return im.resize((im.width // scale, im.height // scale), Image.NEAREST)


def encode(im):
    px = im.load()
    palette, rows = [], []
    for y in range(im.height):
        row = ""
        for x in range(im.width):
            r, g, b, a = px[x, y]
            if a < 128:
                row += "."
                continue
            c = (r << 16) | (g << 8) | b
            if c not in palette:
                palette.append(c)
            row += KEYS[palette.index(c)]
        rows.append(row)
    return palette, rows


def swift_entry(name, im, extra=""):
    palette, rows = encode(im)
    pal = ", ".join("0x%06X" % c for c in palette)
    body = ",\n".join('            "%s"' % r for r in rows)
    return '        Art(name: "%s", palette: [%s]%s, rows: [\n%s,\n        ]),' % (name, pal, extra, body)


HEADER = """import Foundation

// Generated by Tools/tiles_to_swift.py from the design's artwork. Don't edit by hand.

"""

tiles = [("grasstop", True, False), ("dirt", True, False), ("brick", True, False), ("water", False, True),
         ("block", True, False), ("tree", False, False), ("flower", False, False), ("cloud", False, False)]
out = HEADER + "extension StarterTiles {\n    static let art: [Art] = [\n"
for name, solid, hazard in tiles:
    extra = ", solid: %s, hazard: %s" % (str(solid).lower(), str(hazard).lower())
    out += swift_entry(name, native(ASSETS + "tile-%s.png" % name, 6), extra) + "\n"
out += "    ]\n}\n"
open("PixelDeck/Core/StarterTiles.swift", "w").write(out)

stamps = ["heart", "star", "eye", "cloud", "tree", "bush", "mushroom", "sign"]
out = HEADER + "extension StarterStamps {\n    static let art: [Art] = [\n"
for name in stamps:
    out += swift_entry(name, native(ASSETS + "stamp-%s.png" % name)) + "\n"
out += "    ]\n}\n"
open("PixelDeck/Core/StarterStamps.swift", "w").write(out)
print("wrote StarterTiles.swift and StarterStamps.swift")
